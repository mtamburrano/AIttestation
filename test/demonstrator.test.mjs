test('encrypted durable attempt survives interruption without resend', async t => {
  let crash = false;
  const { root, session, egress } = await fixture(t, { fault: phase => { if (crash && phase === 'after-egress') throw Error('simulated interruption'); } });
  session.enroll('test-scope', 'fixture'); const v = await session.freeze(input('Sealed')); await session.confirm({ id: v.id });
  crash = true;
  await assert.rejects(session.release({ id: v.id, scope: v.scope, currentPayload: payload, supported: true }), /interruption/);
  const restarted = await new ReleaseRuntime(root, async () => { throw Error('Unexpected resend'); }, undefined, { store: session.store }).init();
  const state = restarted.snapshot(); assert.equal(Object.values(state.attempts)[0].state, 'OUTCOME_UNKNOWN');
  assert.equal(state.seals[v.id].authorization, null); assert.equal(egress.length, 1);
  await assert.rejects(restarted.release({ id: v.id, scope: v.scope, currentPayload: payload, expectedDigest: v.digest }), /authorization/);
});
test('loopback API requires exact host, UI pairing and same origin', async t => {
  const root = await mkdtemp(join(tmpdir(), 'provenance-demo-http-test-'));
  const app = await startDemo(root); t.after(async () => { await app.close(); await rm(root, { recursive: true, force: true }); });
  const headers = { Origin: app.appOrigin, Authorization: `Bearer ${new URL(app.url).hash.slice(1)}` };
  for (const bad of [{}, { ...headers, Origin: 'https://hostile.invalid' }]) {
    const r = await fetch(`${app.appOrigin}/enroll`, { method: 'POST', headers: bad, body: JSON.stringify({ scope: 'test-scope', policy: 'fixture' }) }); assert.equal(r.status, 400);
  }
  const badHostStatus = await new Promise((resolve, reject) => {
    const req = request(`${app.appOrigin}/enroll`, { method: 'POST', headers: { ...headers, Host: 'hostile.invalid' } }, res => { res.resume(); resolve(res.statusCode); });
    req.on('error', reject); req.end(JSON.stringify({ scope: 'test-scope', policy: 'fixture' }));
  });
  assert.equal(badHostStatus, 400);
  const r = await fetch(`${app.appOrigin}/enroll`, { method: 'POST', headers, body: JSON.stringify({ scope: 'test-scope', policy: 'fixture' }) }); assert.equal(r.status, 200);
  assert.equal((await fetch(`${app.providerOrigin}/visible`, { method: 'POST', body: '{}' })).status, 400);
  assert.equal(app.egress.size, 0);
});
