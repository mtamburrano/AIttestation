import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const directory = new URL('./', import.meta.url);
const files = ['bounded', 'chatgpt', 'fetch-observer', 'main'];
async function observerBundle() {
  const modules = [];
  for (const name of files) {
    const source = await readFile(new URL(`transport/${name}.mjs`, directory), 'utf8');
    modules.push(`// transport/${name}.mjs\n` + source.replace(/^import .*;\n/gm, '').replace(/^export /gm, ''));
  }
  return '// Generated by build-observer.mjs. Edit transport/*.mjs, then rebuild.\n(() => {\n"use strict";\n' + modules.join('\n') + '\n})();\n';
}
const path = new URL('extension/fetch-observer.js', directory);
export async function assertObserverBundle() {
  if (await readFile(path, 'utf8') !== await observerBundle()) throw Error('STALE_OBSERVER_BUNDLE');
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) await assertObserverBundle();
  else await writeFile(path, await observerBundle());
}
